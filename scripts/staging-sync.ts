// npm run staging:sync
// Generates staging-backend/ (committed) from ../job/backend (read-only) + our overlay and patches, the same
// patched backend that `npm run backend:local` runs. Render builds this folder for the staging server (D4, D20).
import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { applyEdits, PATCHES } from './backend-local/patches.ts';
import { shouldCopyStaging, STAGING } from './backend-local/staging.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.resolve(root, '..', 'job', 'backend');
const target = path.join(root, STAGING.rootDir);
const overlaySrc = path.join(root, 'scripts', 'backend-local', 'overlay', 'src');

if (!existsSync(path.join(source, 'package.json'))) {
  console.error(`[staging-sync] Reference backend not found at ${source} (clone ../job first).`);
  process.exit(1);
}

rmSync(target, { recursive: true, force: true });
cpSync(source, target, { recursive: true, filter: (src) => shouldCopyStaging(path.relative(source, src)) });
cpSync(overlaySrc, path.join(target, 'src'), { recursive: true });

for (const patch of PATCHES) {
  const file = path.join(target, patch.file);
  writeFileSync(file, applyEdits(readFileSync(file, 'utf8'), patch.edits, patch.file));
  console.log(`[staging-sync] patched ${patch.file}`);
}

writeFileSync(
  path.join(target, 'README.md'),
  [
    '# Generated: do not edit',
    '',
    'Staging copy of the ApronHanger backend (D4, D20), generated by `npm run staging:sync` from `../job/backend`',
    'plus our local-only patches (OTP test mode, raised OTP limit). Render builds this folder. Edit',
    '`scripts/backend-local/` in this repo and regenerate; never edit these files by hand.',
    '',
  ].join('\n'),
);
console.log(`[staging-sync] wrote ${STAGING.rootDir}/ from ${source}`);
