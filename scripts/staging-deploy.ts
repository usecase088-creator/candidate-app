// npm run staging:deploy
// Creates or updates the staging backend service in the SEPARATE staging Render workspace (RENDER_STAGING_API in
// .env.local, D20). Never uses RENDER_API (the read-only production key). Prints no secrets.
import { randomBytes } from 'node:crypto';
import { appendFileSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { parseEnv } from './backend-local/env.ts';
import { buildRenderServicePayload, buildStagingEnv, STAGING } from './backend-local/staging.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envFile = path.join(root, '.env.local');
const REPO = 'https://github.com/usecase088-creator/candidate-app';
const API = 'https://api.render.com/v1';

const local = parseEnv(readFileSync(envFile, 'utf8'));
const key = local.RENDER_STAGING_API;
if (!key) throw new Error('RENDER_STAGING_API is missing in .env.local');
if (key === local.RENDER_API)
  throw new Error('RENDER_STAGING_API must not be the production key (RENDER_API).');

// A stable secret for this server, kept in .env.local so redeploys don't sign everyone out.
let jwt = local.STAGING_JWT_SECRET;
if (!jwt) {
  jwt = randomBytes(48).toString('hex');
  appendFileSync(
    envFile,
    `\n# JWT secret of the staging backend (generated by npm run staging:deploy)\nSTAGING_JWT_SECRET=${jwt}\n`,
  );
}

async function render<T>(method: string, route: string, body?: unknown): Promise<T> {
  const res = await fetch(`${API}${route}`, {
    method,
    headers: {
      Authorization: `Bearer ${key}`,
      Accept: 'application/json',
      'Content-Type': 'application/json',
    },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const text = await res.text();
  if (!res.ok) throw new Error(`Render ${method} ${route}: HTTP ${res.status} ${text.slice(0, 400)}`);
  return (text ? JSON.parse(text) : undefined) as T;
}

type Service = { id: string; name: string; serviceDetails?: { url?: string } };

const env = buildStagingEnv(local, jwt);
const owners = await render<{ owner: { id: string; name: string } }[]>('GET', '/owners?limit=5');
const owner = owners[0]?.owner;
if (!owner) throw new Error('No Render workspace found for RENDER_STAGING_API.');
console.log(`[staging-deploy] workspace: ${owner.name}`);

const existing = (await render<{ service: Service }[]>('GET', `/services?name=${STAGING.name}&limit=5`)).find(
  (s) => s.service.name === STAGING.name,
)?.service;

let service: Service;
if (existing) {
  console.log(`[staging-deploy] updating env of ${existing.name}`);
  await render(
    'PUT',
    `/services/${existing.id}/env-vars`,
    Object.entries(env).map(([k, value]) => ({ key: k, value })),
  );
  await render('POST', `/services/${existing.id}/deploys`, {});
  service = existing;
} else {
  console.log(`[staging-deploy] creating ${STAGING.name} (free, ${STAGING.region})`);
  const created = await render<{ service: Service }>(
    'POST',
    '/services',
    buildRenderServicePayload({ ownerId: owner.id, repo: REPO, env }),
  );
  service = created.service;
}
console.log(
  `[staging-deploy] service ${service.id}${service.serviceDetails?.url ? ` ${service.serviceDetails.url}` : ''}`,
);

// Wait for the first deploy (build + migrations, a few minutes).
for (let i = 0; i < 60; i++) {
  await new Promise((r) => setTimeout(r, 15_000));
  const deploys = await render<{ deploy: { id: string; status: string } }[]>(
    'GET',
    `/services/${service.id}/deploys?limit=1`,
  );
  const status = deploys[0]?.deploy.status ?? 'unknown';
  console.log(`[staging-deploy] deploy: ${status}`);
  if (status === 'live') break;
  if (['build_failed', 'update_failed', 'canceled', 'pre_deploy_failed'].includes(status)) process.exit(1);
}
const info = await render<Service>('GET', `/services/${service.id}`);
console.log(`[staging-deploy] url: ${info.serviceDetails?.url ?? '(see the Render dashboard)'}`);
